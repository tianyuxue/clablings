package engine

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/tianyuxue/clablings/internal/content"
)

// TopoNode is one node in a topology.
type TopoNode struct {
	Name  string
	Kind  string
	Image string
}

// TopoLink is an undirected link between two endpoints.
type TopoLink struct {
	A     string
	PortA string
	B     string
	PortB string
}

// Topology is a parsed .clab.yml.
type Topology struct {
	Name  string
	Nodes []TopoNode
	Links []TopoLink
}

type rawTopology struct {
	Name     string `yaml:"name"`
	Topology struct {
		Nodes map[string]struct {
			Kind  string `yaml:"kind"`
			Image string `yaml:"image"`
		} `yaml:"nodes"`
		Links []struct {
			Endpoints []string `yaml:"endpoints"`
		} `yaml:"links"`
	} `yaml:"topology"`
}

// ParseTopology parses a .clab.yml file.
func ParseTopology(path string) (*Topology, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var raw rawTopology
	if err := yaml.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("%s: parse topology: %w", path, err)
	}
	t := &Topology{Name: raw.Name}
	if t.Name == "" {
		return nil, fmt.Errorf("%s: missing top-level name", path)
	}
	var nodeNames []string
	for name := range raw.Topology.Nodes {
		nodeNames = append(nodeNames, name)
	}
	sort.Strings(nodeNames)
	for _, name := range nodeNames {
		n := raw.Topology.Nodes[name]
		t.Nodes = append(t.Nodes, TopoNode{Name: name, Kind: n.Kind, Image: n.Image})
	}
	for i, l := range raw.Topology.Links {
		if len(l.Endpoints) != 2 {
			return nil, fmt.Errorf("%s: link %d must have exactly 2 endpoints: %v", path, i, l.Endpoints)
		}
		a, pa, err := splitEndpoint(l.Endpoints[0])
		if err != nil {
			return nil, fmt.Errorf("%s: link %d endpoint %q: %w", path, i, l.Endpoints[0], err)
		}
		b, pb, err := splitEndpoint(l.Endpoints[1])
		if err != nil {
			return nil, fmt.Errorf("%s: link %d endpoint %q: %w", path, i, l.Endpoints[1], err)
		}
		t.Links = append(t.Links, TopoLink{A: a, PortA: pa, B: b, PortB: pb})
	}
	return t, nil
}

func splitEndpoint(s string) (node, port string, err error) {
	i := strings.Index(s, ":")
	if i <= 0 || i == len(s)-1 {
		return "", "", fmt.Errorf("invalid endpoint %q (want node:port)", s)
	}
	return s[:i], s[i+1:], nil
}

// ContainerName returns the long container name generated by containerlab.
func ContainerName(lab, node string) string {
	return "clab-" + lab + "-" + node
}

// ContainerNameFor returns the containerlab container name for an exercise's node.
func ContainerNameFor(ex *content.Exercise, node string) string {
	if ex.ChapterRef != nil && ex.ChapterRef.TopologyName != "" {
		return ContainerName(ex.ChapterRef.TopologyName, node)
	}
	return node
}
